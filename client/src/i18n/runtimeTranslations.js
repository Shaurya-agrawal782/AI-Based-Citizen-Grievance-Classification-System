const phraseTranslations = {
  hi: hiPhrases,
};

function normalizeText(value) {
  return String(value ?? '').replace(/\s+/g, ' ').trim();
}

function preserveOuterWhitespace(original, translated) {
  const source = String(original ?? '');
  const leading = source.match(/^\s*/)?.[0] ?? '';
  const trailing = source.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

function replaceKnownTokens(value, lang) {
  if (lang !== 'hi') return value;

  let next = value;
  const tokens = Object.entries({ ...hiPhrases, ...hiValueTokens })
    .sort((a, b) => b[0].length - a[0].length);

  for (const [english, hindi] of tokens) {
    if (!english || english.length < 3) continue;
    next = next.split(english).join(hindi);
  }

  return next;
}

export function translateUiText(value, lang) {
  if (lang === 'en' || value == null) return value;

  const normalized = normalizeText(value);
  if (!normalized) return value;

  const exact = phraseTranslations[lang]?.[normalized] || (lang === 'hi' ? hiValueTokens[normalized] : undefined);
  if (exact) return preserveOuterWhitespace(value, exact);

  const replaced = replaceKnownTokens(String(value), lang);
  return replaced === value ? value : replaced;
}

export function hasDevanagari(value) {
  return /[\u0900-\u097F]/.test(String(value ?? ''));
}
